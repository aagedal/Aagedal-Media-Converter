import AppKit
import SwiftUI

/// A4 PDF report of the encode statistics: overview and chart on the first
/// page, the rankings on the second. Pages are the SwiftUI views the
/// statistics window uses, rendered in light mode.
@MainActor
enum EncodeStatisticsPDF {
    enum RenderError: LocalizedError {
        case failed

        var errorDescription: String? {
            String(localized: "The PDF report couldn’t be created.")
        }
    }

    private static let pageSize = CGSize(width: 595, height: 842)

    static func render(
        summary: EncodeStatisticsSummary,
        period: StatisticsPeriod,
        macLabel: String,
        includeMacs: Bool,
        deviceLabel: (String) -> String,
        includesSync: Bool,
        generatedAt: Date
    ) throws -> Data {
        let header = StatisticsReportHeader(period: period, macLabel: macLabel, generatedAt: generatedAt)
        let groups = EncodeStatisticsDisplay.rankedGroups(summary, includeMacs: includeMacs, deviceLabel: deviceLabel)
        var pages: [AnyView] = [AnyView(
            StatisticsReportOverviewPage(header: header, summary: summary, period: period, includesSync: includesSync)
        )]
        if !groups.isEmpty {
            pages.append(AnyView(StatisticsReportRankingsPage(header: header, groups: groups)))
        }

        let data = NSMutableData()
        var box = CGRect(origin: .zero, size: pageSize)
        guard let consumer = CGDataConsumer(data: data as CFMutableData),
              let context = CGContext(consumer: consumer, mediaBox: &box, nil) else {
            throw RenderError.failed
        }
        var closed = false
        defer { if !closed { context.closePDF() } }

        for (index, page) in pages.enumerated() {
            let view = page
                .frame(width: pageSize.width, height: pageSize.height, alignment: .top)
                .overlay(alignment: .bottom) {
                    HStack {
                        Text("Generated by Aagedal Media Converter")
                        Spacer()
                        Text(verbatim: "\(index + 1) / \(pages.count)")
                    }
                    .font(.system(size: 8))
                    .foregroundStyle(.secondary)
                    .padding(.horizontal, 38)
                    .padding(.bottom, 20)
                }
                .background(Color.white)
                .environment(\.colorScheme, .light)
            let renderer = ImageRenderer(content: view)
            renderer.proposedSize = ProposedViewSize(pageSize)
            var succeeded = false
            renderer.render { _, draw in
                context.beginPDFPage(nil)
                draw(context)
                context.endPDFPage()
                succeeded = true
            }
            guard succeeded else { throw RenderError.failed }
        }
        // Flush the PDF trailer before copying NSMutableData into a value.
        context.closePDF()
        closed = true
        return data as Data
    }
}

private struct StatisticsReportHeader: View {
    let period: StatisticsPeriod
    let macLabel: String
    let generatedAt: Date

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text("Encode Statistics")
                .font(.system(size: 22, weight: .semibold))
            Text(verbatim: "\(period.label) · \(macLabel) · \(generatedAt.formatted(date: .abbreviated, time: .shortened))")
                .font(.system(size: 11))
                .foregroundStyle(.secondary)
        }
        .frame(maxWidth: .infinity, alignment: .leading)
    }
}

private struct StatisticsReportOverviewPage: View {
    let header: StatisticsReportHeader
    let summary: EncodeStatisticsSummary
    let period: StatisticsPeriod
    let includesSync: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 18) {
            header
            StatisticsReportSection(title: String(localized: "Overview")) {
                ForEach(EncodeStatisticsDisplay.overviewRows(summary)) { row in
                    StatisticsReportRow(label: row.title, value: row.value, tint: row.tint)
                }
            }
            StatisticsReportSection(title: String(localized: "Encodes over Time")) {
                EncodeStatisticsChart(summary: summary, period: period)
                    .frame(height: 240)
            }
            VStack(alignment: .leading, spacing: 4) {
                if summary.includesRollups {
                    Text("Includes monthly summaries of encodes older than the history retention period.")
                }
                if includesSync {
                    Text("History sync is on, so the statistics include the encodes of your other Macs.")
                }
            }
            .font(.system(size: 9))
            .foregroundStyle(.secondary)
        }
        .padding(38)
    }
}

private struct StatisticsReportRankingsPage: View {
    let header: StatisticsReportHeader
    let groups: [StatisticsRankedGroup]

    var body: some View {
        VStack(alignment: .leading, spacing: 18) {
            header
            ForEach(groups) { group in
                StatisticsReportSection(title: group.title) {
                    ForEach(group.items) { item in
                        StatisticsReportRow(label: item.label, value: "\(item.count)")
                    }
                }
            }
        }
        .padding(38)
    }
}

private struct StatisticsReportSection<Content: View>: View {
    let title: String
    @ViewBuilder let content: Content

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            Text(verbatim: title)
                .font(.system(size: 13, weight: .semibold))
            Divider()
            content
        }
    }
}

private struct StatisticsReportRow: View {
    let label: String
    let value: String
    var tint: Color?

    var body: some View {
        HStack {
            Text(verbatim: label)
                .lineLimit(1)
                .truncationMode(.middle)
            Spacer()
            Text(verbatim: value)
                .monospacedDigit()
                .foregroundStyle(tint ?? .primary)
        }
        .font(.system(size: 11))
    }
}
